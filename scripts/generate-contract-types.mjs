import { readFile, writeFile } from 'node:fs/promises';
import openapiTS, { astToString } from 'openapi-typescript';

const check = process.argv.includes('--check');
const document = new URL('../contracts/openapi.json', import.meta.url);
const fixturePath = new URL('../contracts/fixtures/demo.json', import.meta.url);
const generatedPath = new URL('../apps/web/src/api/generated.ts', import.meta.url);
const fixtureOutput = new URL('../apps/web/src/api/fixtures.generated.ts', import.meta.url);
const header = '// GENERATED by npm run contracts:generate. Do not edit.\n';
const types = header + astToString(await openapiTS(document));
const fixture = JSON.parse(await readFile(fixturePath, 'utf8'));
const fixtureCode =
  header +
  "import type { ContractCatalog } from './types';\n\n" +
  'export const mockFixtures = ' +
  JSON.stringify(fixture, null, 2) +
  ' as const satisfies ContractCatalog;\n';

for (const [path, output] of [
  [generatedPath, types],
  [fixtureOutput, fixtureCode],
]) {
  if (check) {
    if ((await readFile(path, 'utf8')) !== output) {
      throw new Error(`Generated contract drift: ${path.pathname}; run npm run contracts:generate`);
    }
  } else {
    await writeFile(path, output, 'utf8');
  }
}
console.log(
  check
    ? 'Generated TypeScript and fixtures match Pydantic.'
    : 'Generated TypeScript and demo fixtures.',
);
